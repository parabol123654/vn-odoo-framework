#: Keep the shipped expression of a line when the database has these accounts.
#: B02-DN 23 used to read 6351, which is not a TT200 account; a company that
#: opened 6351 for interest expense keeps it rather than lose the figure.
KEEP_IF_ACCOUNTS = {'b02dn_23': ('expression', '6351')}


def _ref(env, xmlid):
    record = env.ref('%s.%s' % (MODULE, xmlid), raise_if_not_found=False)
    return record.id if record else None


def _resolve(env, model, name, value):
    """-> the shipped value in the form _norm gives the stored one."""
    field = env[model]._fields[name]
    if value == DEFAULT:
        value = env[model].default_get([name]).get(name)
    if isinstance(value, tuple) and value[0] == 'ref':
        return _ref(env, value[1])
    return _norm(field, value)


def _norm(field, value):
    if hasattr(value, '_name'):
        return value.id or None
    if value in (None, False, ''):
        return None
    if field.type == 'integer':
        return int(value)
    if field.type == 'float':
        return round(float(value), 6)
    if field.type == 'boolean':
        return bool(value) or None
    return value


def _account_exists(env, prefix):
    Account = env['account.account'].with_context(active_test=False)
    return any(Account.with_company(company).search_count(
        [('code', '=like', prefix + '%')])
        for company in env['res.company'].search([]))


def migrate(cr, version):
    env = api.Environment(cr, SUPERUSER_ID, {})
    updated, removed, kept = 0, 0, []
    for xmlid, (model, old) in OLD.items():
        record = env.ref('%s.%s' % (MODULE, xmlid), raise_if_not_found=False)
        if not record:
            continue
        def differs(shipped):
            return [name for name, value in shipped.items()
                    if name in record._fields and
                    _norm(record._fields[name], record[name])
                    != _resolve(env, model, name, value)]
        edited = differs(old)
        if edited and xmlid in NEW and not differs(NEW[xmlid]):
            continue  # created by this upgrade, or already corrected
        if edited:
            kept.append('%s (%s)' % (xmlid, ', '.join(edited)))
            continue
        new = NEW.get(xmlid)
        if new is None:
            record.unlink()
            removed += 1
            continue
        values = {}
        for name, value in new.items():
            if name not in record._fields or value == old.get(name):
                continue
            if value == DEFAULT:
                value = env[model].default_get([name]).get(name, False)
            elif isinstance(value, tuple) and value[0] == 'ref':
                value = _ref(env, value[1])
            values[name] = value
        keep = KEEP_IF_ACCOUNTS.get(xmlid)
        if keep and keep[0] in values and _account_exists(env, keep[1]):
            _logger.info('%s: accounts %s exist, keeping %s = %r.',
                         xmlid, keep[1], keep[0], record[keep[0]])
            values.pop(keep[0])
        record.write(values)
        updated += 1
    _logger.info('Shipped data: %d records corrected, %d removed.',
                 updated, removed)
    if kept:
        _logger.warning(
            'Shipped data: %d records were edited on this database and kept '
            'as they are; compare them with the module data: %s',
            len(kept), '; '.join(kept))
