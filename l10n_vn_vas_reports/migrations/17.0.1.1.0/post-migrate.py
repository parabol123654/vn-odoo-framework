def _current(line):
    return {
        'code': line.code or '', 'name': line.name or '',
        'sequence': line.sequence, 'level': line.level,
        'expression': line.expression or '', 'formula': line.formula or '',
        'sign': line.sign, 'side': line.side,
        'split_by_partner': bool(line.split_by_partner),
        'bold': bool(line.bold), 'movement_side': line.movement_side or 'net',
        'maturity': line.maturity or 'all',
    }


def migrate(cr, version):
    from odoo import api, SUPERUSER_ID
    env = api.Environment(cr, SUPERUSER_ID, {})
    updated, removed, kept = 0, 0, []
    for xmlid, old in OLD.items():
        line = env.ref('%s.%s' % (MODULE, xmlid), raise_if_not_found=False)
        if not line:
            continue
        current = _current(line)
        if any(current[f] != old[f] for f in LINE_FIELDS):
            kept.append('%s (%s)' % (xmlid, current['code']))
            continue
        new = NEW.get(xmlid)
        if new is None:
            line.unlink()
            removed += 1
        else:
            line.write({f: new[f] for f in LINE_FIELDS})
            updated += 1
    for xmlid, fields in HEADS.items():
        mapping = env.ref('%s.%s' % (MODULE, xmlid), raise_if_not_found=False)
        if not mapping:
            continue
        values = {f: v for f, v in fields.items()
                  if f != 'sequence' and not mapping[f]}
        if values:
            mapping.write(values)
    _logger.info('Statement mappings: %d shipped lines corrected, %d removed.',
                 updated, removed)
    if kept:
        _logger.warning(
            'Statement mappings: %d shipped lines were edited on this database '
            'and kept as they are; compare them with the module data: %s',
            len(kept), ', '.join(kept))
